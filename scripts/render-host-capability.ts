#!/usr/bin/env bun
/**
 * Render host capability matrix (docs/specs/tri-host-capability-alignment.spec.md D1, D2; AC1).
 *
 * Explicitly imports the three composition-root declarations:
 * - Claude Code: plugins/immune-brain/runtime/claude/capability.ts
 * - Antigravity: plugins/immune-brain/runtime/antigravity/capability.ts
 * - Pi: plugins/immune-brain/.pi-extension/pi-capability.ts
 *
 * Renders docs/reference/host-capability.md.
 * No runtime lookup or dynamic dispatch is performed.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import {
	CAPABILITY_PORT_IDS,
	CAPABILITY_PORTS,
	type HostCapabilityDeclaration,
	validateHostCapabilityDeclaration,
} from "../plugins/immune-brain/runtime/host-core/capability";
import { CLAUDE_CAPABILITY } from "../plugins/immune-brain/runtime/claude/capability";
import { ANTIGRAVITY_CAPABILITY } from "../plugins/immune-brain/runtime/antigravity/capability";
import { PI_CAPABILITY } from "../plugins/immune-brain/.pi-extension/pi-capability";

export const HOST_CAPABILITY_PATH = "docs/reference/host-capability.md";

export function renderHostCapabilityMatrix(
	declarations: HostCapabilityDeclaration[] = [
		CLAUDE_CAPABILITY,
		ANTIGRAVITY_CAPABILITY,
		PI_CAPABILITY,
	],
): string {
	// Validate each declaration to ensure complete and correct coverage
	const validated = declarations.map((d) => validateHostCapabilityDeclaration(d));

	const seenHosts = new Set<string>();
	for (const d of validated) {
		if (seenHosts.has(d.hostId)) {
			throw new Error(`Duplicate host declaration in matrix renderer: ${d.hostId}`);
		}
		seenHosts.add(d.hostId);
	}

	const hosts = validated.map((d) => ({
		id: d.hostId,
		name: d.hostName,
	}));

	const lines: string[] = [
		"# Host Capability Matrix",
		"",
		"<!-- This document is generated by scripts/render-host-capability.ts. Do not hand-edit. -->",
		"",
		"This reference documents the capability contract and evidence levels for Immune-Brain host adapters across ports P1–P9 (defined in [ADR 0039](../adr/0039-host-capability-profiles.md)).",
		"",
		"> [!IMPORTANT]",
		"> Capability declarations are documentation and conformance inputs only, never runtime dispatch (ADR 0004, ADR 0039). The runtime performs no capability-based registry lookup or dynamic host dispatch.",
		"",
		"## Evidence Levels",
		"",
		"- `certified`: Verified with real host end-to-end evidence and passed lifecycle certification.",
		"- `conformance-only`: Verified against local conformance test suites, without live host certification.",
		"- `guard-only`: Protected by defensive runtime checks (e.g. tree guard), with known residual limitations disclosed.",
		"- `unsupported`: Not supported by the host adapter, with reason documented.",
		"",
		"## Capability Matrix",
		"",
		`| Port | Capability | ${hosts.map((h) => h.name).join(" | ")} |`,
		`| --- | --- | ${hosts.map(() => "---").join(" | ")} |`,
	];

	for (const portId of CAPABILITY_PORT_IDS) {
		const portDef = CAPABILITY_PORTS[portId];
		const hostCells = validated.map((d) => {
			const cell = d.ports[portId];
			return `\`${cell.level}\``;
		});
		lines.push(`| ${portId} | ${portDef.name} | ${hostCells.join(" | ")} |`);
	}

	lines.push("");
	lines.push("## Detailed Evidence and Limitations");
	lines.push("");

	for (const portId of CAPABILITY_PORT_IDS) {
		const portDef = CAPABILITY_PORTS[portId];
		lines.push(`### ${portId} — ${portDef.name}`);
		lines.push("");
		lines.push(`_${portDef.description}_`);
		lines.push("");
		for (const d of validated) {
			const cell = d.ports[portId];
			lines.push(`- **${d.hostName}** (\`${cell.level}\`): ${cell.evidence}`);
		}
		lines.push("");
	}

	return lines.join("\n").trimEnd() + "\n";
}

function main(): void {
	const root = resolve(import.meta.dir, "..");
	const targetPath = resolve(root, HOST_CAPABILITY_PATH);
	const rendered = renderHostCapabilityMatrix();
	const isCheck = process.argv.includes("--check");

	if (isCheck) {
		if (!existsSync(targetPath)) {
			console.error(`Missing target file: ${HOST_CAPABILITY_PATH}`);
			process.exit(1);
		}
		const existing = readFileSync(targetPath, "utf8");
		if (existing !== rendered) {
			console.error(`${HOST_CAPABILITY_PATH} is out of sync with capability declarations. Run 'bun scripts/render-host-capability.ts' to regenerate.`);
			process.exit(1);
		}
		console.log(`${HOST_CAPABILITY_PATH} is in sync.`);
		return;
	}

	writeFileSync(targetPath, rendered, "utf8");
	console.log(`Rendered ${HOST_CAPABILITY_PATH}`);
}

if (import.meta.main) {
	main();
}
