#!/usr/bin/env bun
import {
	chmodSync,
	existsSync,
	lstatSync,
	mkdirSync,
	mkdtempSync,
	readdirSync,
	readFileSync,
	rmSync,
	statSync,
	writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { tmpdir } from "node:os";
import { spawnSync } from "node:child_process";
import { stampPluginManifest, validateManifests } from "./plugin_versioning";
import {
	generateReadonlyRoleDefinitions,
	generateReviewerDefinition,
	generateVerifierDefinition,
} from "./build-claude-plugin";
import { INTERNAL_ROLE_PROMPTS } from "../plugins/immune-brain/runtime/role_prompt_bridge";

/** The shared source root: Pi/Claude install root and canonical delivery inputs. */
export const SHARED_ROOT = "plugins/immune-brain";
/** The independently installable Antigravity plugin root. */
export const ANTIGRAVITY_ROOT = "plugins/immune-brain-antigravity";

const SRC = `${SHARED_ROOT}/runtime/antigravity/mcp_server.ts`;
const BUNDLE = "dist/antigravity/mcp-server.mjs";

/**
 * Files maintained by hand inside the Antigravity root. Everything else under
 * the root is generated by this builder and owned by `--check`.
 */
export const CANONICAL_FILES = [
	".antigravity-plugin/plugin.json",
	"mcp_config.json",
	"hooks.json",
	"README.md",
] as const;

/**
 * Native tool names the generated role definitions may use. A native
 * definition declares its allowlist as a YAML array; none of these tools can
 * write, execute a shell command or dispatch another agent.
 */
export const NATIVE_READONLY_TOOLS = ["view_file", "grep_search", "list_dir", "find_by_name"] as const;

const IGNORED_NAMES = new Set([".DS_Store", ".gitignore", ".ignore"]);
/** Host output directories under the shared `dist/`; never copied (no recursion, no Claude bundle). */
const EXCLUDED_DIST_DIRS = new Set(["claude", "antigravity"]);

interface OwnedFile {
	content: Buffer;
	executable: boolean;
}

type OwnedFiles = Map<string, OwnedFile>;

function toPosix(path: string): string {
	return path.split(sep).join("/");
}

function walk(dir: string, visit: (absolute: string, relativePath: string) => void, base = dir): void {
	if (!existsSync(dir)) return;
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		const absolute = join(dir, entry.name);
		if (entry.isDirectory()) walk(absolute, visit, base);
		else visit(absolute, toPosix(relative(base, absolute)));
	}
}

function addFile(files: OwnedFiles, path: string, absolute: string): void {
	files.set(path, { content: readFileSync(absolute), executable: (statSync(absolute).mode & 0o111) !== 0 });
}

function addTree(
	files: OwnedFiles,
	source: string,
	destination: string,
	skipDir: (relativeDir: string) => boolean = () => false,
): void {
	if (!existsSync(source)) throw new Error(`Missing shared delivery input: ${toPosix(source)}`);
	if (!statSync(source).isDirectory()) {
		addFile(files, destination, source);
		return;
	}
	walk(source, (absolute, relativePath) => {
		const segments = relativePath.split("/");
		if (segments.some((segment) => IGNORED_NAMES.has(segment))) return;
		for (let i = 1; i < segments.length; i++) if (skipDir(segments.slice(0, i).join("/"))) return;
		addFile(files, `${destination}/${relativePath}`.replace(/^\//, ""), absolute);
	});
}

function runtimeEntries(root: string): string[] {
	const manifest = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8"));
	const prefix = `${SHARED_ROOT}/runtime/`;
	const entries = (manifest.files as string[]).filter((entry) => entry.startsWith(prefix));
	if (entries.length === 0) throw new Error("package.json files declares no runtime entries to ship");
	return entries;
}

function nativeDefinition(claudeDefinition: string): { file: string; content: string } {
	const match = /^---\nname: ([^\n]+)\ndescription: ([^\n]+)\ntools: [^\n]*\n---\n\n([\s\S]*)$/.exec(claudeDefinition);
	if (!match) throw new Error("shared role definition has an unexpected frontmatter shape");
	const [, name, description, body] = match;
	return {
		file: `agents/${name}.md`,
		content: [
			"---",
			`name: ${name}`,
			`description: ${JSON.stringify(description)}`,
			"mainAgent: false",
			"subagent: true",
			"excludeDefaultComponents: true",
			"inheritMcp: false",
			"tools:",
			...NATIVE_READONLY_TOOLS.map((tool) => `  - ${tool}`),
			"---",
			"",
			body,
		].join("\n"),
	};
}

function requireCanonicalInputs(root: string): void {
	for (const file of CANONICAL_FILES) {
		if (!existsSync(resolve(root, ANTIGRAVITY_ROOT, file))) {
			throw new Error(`Missing canonical Antigravity input: ${ANTIGRAVITY_ROOT}/${file}`);
		}
	}
	for (const file of [".antigravity-plugin/plugin.json", "mcp_config.json", "hooks.json"]) {
		try {
			JSON.parse(readFileSync(resolve(root, ANTIGRAVITY_ROOT, file), "utf8"));
		} catch (error) {
			throw new Error(`Malformed JSON in ${ANTIGRAVITY_ROOT}/${file}: ${(error as Error).message}`);
		}
	}
	for (const [role, spec] of Object.entries(INTERNAL_ROLE_PROMPTS)) {
		const prompt = resolve(root, SHARED_ROOT, "dist", "role-prompts", spec.file);
		if (!existsSync(prompt)) throw new Error(`Missing role prompt for ${role}: ${SHARED_ROOT}/dist/role-prompts/${spec.file}`);
	}
}

function compile(root: string, outfile: string): void {
	mkdirSync(dirname(outfile), { recursive: true });
	const result = spawnSync("bun", ["build", SRC, "--target=node", "--outfile", outfile, "--packages=bundle"], {
		cwd: root,
		encoding: "utf8",
	});
	if (result.status !== 0) throw new Error(result.stderr || result.stdout || "bun build failed");
}

/** Every file this builder owns under the Antigravity root, keyed by root-relative path. */
function expectedArtifact(root: string): OwnedFiles {
	requireCanonicalInputs(root);
	const shared = resolve(root, SHARED_ROOT);
	const files: OwnedFiles = new Map();

	addTree(files, resolve(shared, "skills"), "skills");
	addTree(files, resolve(shared, "bin"), "bin");
	for (const entry of runtimeEntries(root)) {
		const rel = entry.slice(`${SHARED_ROOT}/`.length);
		addTree(files, resolve(root, entry), rel);
	}
	addTree(files, resolve(shared, "dist"), "dist", (dir) => EXCLUDED_DIST_DIRS.has(dir));
	addFile(files, "BASELINE.md", resolve(shared, "BASELINE.md"));

	for (const definition of [
		generateReviewerDefinition(root),
		generateVerifierDefinition(root),
		...generateReadonlyRoleDefinitions(root).map((generated) => generated.content),
	]) {
		const native = nativeDefinition(definition);
		files.set(native.file, { content: Buffer.from(native.content), executable: false });
	}

	const scratch = mkdtempSync(join(tmpdir(), "antigravity-bundle-"));
	try {
		const bundle = join(scratch, "mcp-server.mjs");
		compile(root, bundle);
		files.set(BUNDLE, { content: readFileSync(bundle), executable: false });
	} finally {
		rmSync(scratch, { recursive: true, force: true });
	}
	return files;
}

function ownedFiles(root: string): Map<string, string> {
	const base = resolve(root, ANTIGRAVITY_ROOT);
	const canonical = new Set<string>(CANONICAL_FILES);
	const owned = new Map<string, string>();
	walk(base, (absolute, relativePath) => {
		if (canonical.has(relativePath) || relativePath.split("/").includes(".DS_Store")) return;
		owned.set(relativePath, absolute);
	});
	return owned;
}

function pruneEmptyDirs(dir: string): boolean {
	if (!existsSync(dir)) return true;
	let empty = true;
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		const child = join(dir, entry.name);
		if (entry.isDirectory() && pruneEmptyDirs(child)) rmSync(child, { recursive: true, force: true });
		else empty = false;
	}
	return empty;
}

export function buildAntigravityPlugin(root = resolve(import.meta.dir, "..")): { out: string; version: string } {
	const { version } = stampPluginManifest(root);
	const expected = expectedArtifact(root);
	const base = resolve(root, ANTIGRAVITY_ROOT);
	for (const [path, absolute] of ownedFiles(root)) if (!expected.has(path)) rmSync(absolute, { force: true });
	for (const [path, file] of expected) {
		const absolute = resolve(base, path);
		mkdirSync(dirname(absolute), { recursive: true });
		const mode = file.executable ? 0o755 : 0o644;
		writeFileSync(absolute, file.content, { mode });
		// `writeFileSync` applies `mode` only when it creates the file; repair a drifted existing one.
		chmodSync(absolute, mode);
	}
	pruneEmptyDirs(base);
	const problems = [...artifactBoundaryErrors(base), ...artifactClosureErrors(base)];
	if (problems.length > 0) throw new Error(`Antigravity artifact invalid:\n${problems.join("\n")}`);
	return { out: resolve(base, BUNDLE), version };
}

/**
 * Differences between the committed owned inventory and a fresh generate.
 * Read-only: nothing is stamped, repaired or left in the worktree.
 */
export function antigravityArtifactDrift(root: string): string[] {
	const expected = expectedArtifact(root);
	const actual = ownedFiles(root);
	const drift: string[] = [];
	for (const [path, file] of expected) {
		const absolute = actual.get(path);
		if (!absolute) drift.push(`missing generated file: ${ANTIGRAVITY_ROOT}/${path}`);
		else if (!readFileSync(absolute).equals(file.content)) drift.push(`changed generated file: ${ANTIGRAVITY_ROOT}/${path}`);
		else if (((statSync(absolute).mode & 0o111) !== 0) !== file.executable) drift.push(`mode drift: ${ANTIGRAVITY_ROOT}/${path}`);
	}
	for (const path of actual.keys()) if (!expected.has(path)) drift.push(`stale generated file: ${ANTIGRAVITY_ROOT}/${path}`);
	return drift;
}

export function checkAntigravityPlugin(root = resolve(import.meta.dir, "..")): void {
	validateManifests(root);
	const drift = antigravityArtifactDrift(root);
	if (drift.length > 0) {
		throw new Error(`${ANTIGRAVITY_ROOT} drifted from a fresh generate of its sources:\n${drift.join("\n")}`);
	}
	const base = resolve(root, ANTIGRAVITY_ROOT);
	const problems = [...artifactBoundaryErrors(base), ...artifactClosureErrors(base)];
	if (problems.length > 0) throw new Error(`Antigravity artifact invalid:\n${problems.join("\n")}`);
}

/** Host-loader components of other hosts; none may appear in the Antigravity root. */
const FOREIGN_COMPONENTS = [".claude-plugin", ".mcp.json", "plugin.json", "hooks", ".pi-extension", "dist/claude"] as const;

function frontmatterOf(text: string): string[] | null {
	const match = /^---\n([\s\S]*?)\n---\n/.exec(text);
	return match ? match[1].split("\n") : null;
}

/**
 * Package-boundary rules for an artifact directory: no component owned by
 * another host's loader, and every native role definition declares `tools` as a
 * YAML array drawn only from the read-only native tool set. Transitive
 * `runtime/claude/` implementation modules are not loader components and stay allowed.
 */
export function artifactBoundaryErrors(artifact: string): string[] {
	const base = resolve(artifact);
	const errors: string[] = [];
	for (const component of FOREIGN_COMPONENTS) {
		if (existsSync(join(base, component))) errors.push(`foreign host component in artifact: ${component}`);
	}
	const agents = join(base, "agents");
	for (const entry of existsSync(agents) ? readdirSync(agents) : []) {
		if (!entry.endsWith(".md")) {
			errors.push(`agents/${entry}: not a native role definition`);
			continue;
		}
		const lines = frontmatterOf(readFileSync(join(agents, entry), "utf8"));
		const toolsAt = lines?.findIndex((line) => line.startsWith("tools:")) ?? -1;
		if (!lines || toolsAt < 0) {
			errors.push(`agents/${entry}: missing tools declaration`);
			continue;
		}
		const inline = lines[toolsAt].slice("tools:".length).trim();
		let tools: string[];
		if (inline) {
			const flow = /^\[(.*)\]$/.exec(inline);
			if (!flow) {
				errors.push(`agents/${entry}: tools must be a YAML array, not a string`);
				continue;
			}
			tools = flow[1].split(",").map((tool) => tool.trim()).filter(Boolean);
		} else {
			tools = [];
			for (const line of lines.slice(toolsAt + 1)) {
				const item = /^\s+-\s+(\S+)\s*$/.exec(line);
				if (!item) break;
				tools.push(item[1]);
			}
		}
		const allowed: readonly string[] = NATIVE_READONLY_TOOLS;
		if (tools.length === 0) errors.push(`agents/${entry}: empty tools declaration`);
		for (const tool of tools) if (!allowed.includes(tool)) errors.push(`agents/${entry}: tool outside the read-only native set: ${tool}`);
	}
	return errors;
}

const LINK = /\]\(([^)\s]+)\)/g;
const RELATIVE_IMPORT = /(?:from|import)\s*\(?\s*["'](\.{1,2}\/[^"']+)["']/g;

function resolvesInside(base: string, from: string, target: string): { path: string; inside: boolean } {
	const path = resolve(dirname(from), target);
	return { path, inside: path === base || path.startsWith(base + sep) };
}

/**
 * Reference closure of an artifact directory, independent of any sibling:
 * public skill and contract links, the role prompts the runtime loads, CLI
 * wrapper runtime targets, configured hook and MCP entrypoints, relative
 * runtime imports, and the absence of symlinks. Empty means closed.
 */
export function artifactClosureErrors(artifact: string): string[] {
	const base = resolve(artifact);
	const errors: string[] = [];
	const files: string[] = [];
	const visit = (dir: string): void => {
		for (const entry of readdirSync(dir, { withFileTypes: true })) {
			const absolute = join(dir, entry.name);
			if (lstatSync(absolute).isSymbolicLink()) errors.push(`symlink in artifact: ${toPosix(relative(base, absolute))}`);
			else if (entry.isDirectory()) visit(absolute);
			else files.push(absolute);
		}
	};
	visit(base);

	const rel = (absolute: string): string => toPosix(relative(base, absolute));
	const requireFile = (absolute: string, why: string): void => {
		if (!existsSync(absolute)) errors.push(`${why}: missing ${rel(absolute)}`);
	};

	for (const absolute of files) {
		const path = rel(absolute);
		const isContract = /^skills\/[^/]+\/SKILL\.md$/.test(path) || /^dist\/.+\.md$/.test(path);
		if (isContract) {
			for (const match of readFileSync(absolute, "utf8").matchAll(LINK)) {
				const target = match[1].split("#")[0];
				if (!target || /^[a-z][a-z0-9+.-]*:/i.test(target)) continue;
				const resolved = resolvesInside(base, absolute, target);
				if (!resolved.inside) errors.push(`${path}: link leaves the artifact: ${match[1]}`);
				else if (!existsSync(resolved.path)) errors.push(`${path}: broken link ${match[1]}`);
			}
		}
		if (path.endsWith(".ts")) {
			for (const match of readFileSync(absolute, "utf8").matchAll(RELATIVE_IMPORT)) {
				const resolved = resolvesInside(base, absolute, match[1]);
				const candidates = [resolved.path, `${resolved.path}.ts`, join(resolved.path, "index.ts")];
				if (!resolved.inside) errors.push(`${path}: import leaves the artifact: ${match[1]}`);
				else if (!candidates.some((candidate) => existsSync(candidate) && statSync(candidate).isFile())) {
					errors.push(`${path}: unresolved runtime import ${match[1]}`);
				}
			}
		}
		if (/^bin\/imm-(kernel|plan|tracker)$/.test(path)) {
			const target = /"\$PLUGIN_ROOT\/([^"]+)"/.exec(readFileSync(absolute, "utf8"));
			if (!target) errors.push(`${path}: wrapper has no runtime target`);
			else requireFile(resolve(base, target[1]), `${path} runtime`);
		}
	}

	for (const [role, spec] of Object.entries(INTERNAL_ROLE_PROMPTS)) {
		requireFile(resolve(base, "dist", "role-prompts", spec.file), `role prompt ${role}`);
	}

	const hooks = resolve(base, "hooks.json");
	if (existsSync(hooks)) {
		for (const match of readFileSync(hooks, "utf8").matchAll(/node \\"\.\/([^"\\]+)\\"/g)) requireFile(resolve(base, match[1]), "hook command");
	}
	const mcp = resolve(base, "mcp_config.json");
	if (existsSync(mcp)) {
		for (const match of readFileSync(mcp, "utf8").matchAll(/\$\{PLUGIN_ROOT\}\/([^"]+)/g)) requireFile(resolve(base, match[1]), "MCP server");
	}
	return errors;
}

if (import.meta.main) {
	if (process.argv.includes("--check")) {
		checkAntigravityPlugin();
		console.log("antigravity plugin artifact is current");
	} else {
		const built = buildAntigravityPlugin();
		console.log(`built ${built.out} @ ${built.version}`);
	}
}
